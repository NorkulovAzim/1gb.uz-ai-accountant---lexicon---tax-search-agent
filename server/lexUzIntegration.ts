export function buildLexUzSearchUrl(query: string): string {
  const enc = encodeURIComponent(query.trim());
  return `https://lex.uz/search/natsearch?all=${enc}`;
}

export function findLexUzSourcesForQuery(query: string, taxArticle?: string): LexUzSource[] {
  const clean = query.toLowerCase().trim();
  const matched: LexUzSource[] = [];

  // Match by keywords or taxArticle
  for (const act of LEX_UZ_CORE_ACTS) {
    const isKeywordMatch = act.keywords.some(
      (kw) => clean.includes(kw) || kw.includes(clean)
    );
    const isTaxArticleMatch = taxArticle && (
      (taxArticle.includes('НК') && act.id === 'lex-tax-code') ||
      (taxArticle.includes('БҲМС 21') && act.id === 'lex-bhms-21') ||
      (taxArticle.includes('489') && act.id === 'lex-pkm-489-esf') ||
      (taxArticle.includes('БҲМС 5') && act.id === 'lex-bhms-5-os') ||
      (taxArticle.includes('БҲМС 4') && act.id === 'lex-bhms-4-tmc') ||
      (taxArticle.includes('Трудовой') && act.id === 'lex-labor-code') ||
      (taxArticle.includes('249') && act.id === 'lex-pkm-249-mxik') ||
      (taxArticle.includes('424') && act.id === 'lex-pkm-424-safari')
    );

    if (isKeywordMatch || isTaxArticleMatch) {
      matched.push(act);
    }
  }

  // Always make sure Tax Code is included for tax terms
  if (
    matched.length === 0 ||
    clean.includes('налог') ||
    clean.includes('солиқ') ||
    clean.includes('ндс') ||
    clean.includes('ққс')
  ) {
    if (!matched.some((m) => m.id === 'lex-tax-code')) {
      const taxCode = LEX_UZ_CORE_ACTS.find((a) => a.id === 'lex-tax-code');
      if (taxCode) matched.push(taxCode);
    }
  }

  // Fallback dynamic Lex.uz source if no exact predefined act matched
  if (matched.length === 0) {
    matched.push({
      id: `lex-dynamic-${Date.now()}`,
      titleRu: `Поиск актов законодательства РУз по слову «${query}» на Lex.uz`,
      titleUz: `«${query}» сўзи бўйича Lex.uz қонунчилик ҳужжатлари қидируви`,
      actType: 'Закон',
      docId: 'search',
      url: buildLexUzSearchUrl(query),
      status: 'Официальный текст',
      descriptionRu: `Официальный поиск в Национальной базе законодательства Республики Узбекистан (lex.uz) по запросу «${query}».`,
      descriptionUz: `Ўзбекистон Республикаси Қонунчилик маълумотлари миллий базаси (lex.uz) бўйича «${query}» расмий қидируви.`,
      keywords: [clean],
    });
  }

  return matched;
}
